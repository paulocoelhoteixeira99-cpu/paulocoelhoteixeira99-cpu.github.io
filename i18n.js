  function init() {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (!originals[key]) {
        originals[key] = el.innerHTML;
      }
    });
    var saved = localStorage.getItem('portfolio-lang');
    if (saved === 'pt') setLang('pt');
  }

  function setLang(lang) {
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (lang === 'pt') {
        el.innerHTML = pt[key] || originals[key] || el.innerHTML;
      } else {
        el.innerHTML = originals[key] || el.innerHTML;
      }
    });
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
    localStorage.setItem('portfolio-lang', lang);
    var btn = document.getElementById('lang-toggle');
    if (btn) {
      btn.textContent = lang === 'pt' ? 'EN' : 'PT';
      btn.setAttribute('aria-label',
        lang === 'pt' ? 'Switch to English' : 'Mudar para Portugu\u00eas');
    }
  }

  window.toggleLang = function () {
    var current = localStorage.getItem('portfolio-lang') || 'en';
    setLang(current === 'en' ? 'pt' : 'en');
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
